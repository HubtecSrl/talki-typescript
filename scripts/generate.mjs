#!/usr/bin/env node
/**
 * Generate `src/generated/` from `openapi/talki-v1.yaml`.
 *
 *     node scripts/generate.mjs           # write the files
 *     node scripts/generate.mjs --check   # CI: fail if they are stale
 *
 * - `schema.ts`: the spec's types, by openapi-typescript (pinned in
 *   package.json). A string whose values are listed in `x-extensible-enum`,
 *   or an enum whose description says new values may be added, becomes a
 *   union of those values and `(string & {})`, so an editor suggests them and
 *   a new one still type-checks.
 * - `models.ts`: one alias per schema (`Call`, `AppointmentCreate`, …).
 * - `resources.ts`: one class per tag (`talki.calls`, …) with one method per
 *   operation, its `withRawResponse` twin, and the `Resources` base `Talki`
 *   extends.
 * - `api-version.ts`: `API_VERSION`, the spec's `info.version`.
 *
 * A method is named after its operation, less the tag's noun (`listCalls` in
 * `calls` is `list`, `getCallTranscript` is `getTranscript`), unless the noun
 * is the first word, the verb (`tagContact` in `tags`). Operations of one tag
 * that would share a name both keep their own (`exportCall`, `exportCalls`).
 */

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import { parse } from "yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = join(ROOT, "openapi", "talki-v1.yaml");
const OUT = join(ROOT, "src", "generated");
const BANNER = "// Generated by scripts/generate.mjs from openapi/talki-v1.yaml. Do not edit: regenerate.\n";

// Names the package exports by hand: a schema of the same name would be
// shadowed by them.
const RESERVED = new Set([
  "Talki",
  "TalkiOptions",
  "TalkiError",
  "ApiError",
  "InvalidRequestError",
  "AuthenticationError",
  "PermissionDeniedError",
  "ConflictError",
  "RateLimitError",
  "ServerError",
  "ConnectionError",
  "RequestTimeoutError",
  "PaginationError",
  "OAuthError",
  "OAuthApp",
  "SignatureVerificationError",
  "Page",
  "PagePromise",
  "RawResponse",
  "RequestOptions",
  "Logger",
  "LogLevel",
  "TokenSet",
  "Pkce",
  "Resources",
  "WebhookEvent",
]);
// The options a method takes besides the query: none may be a query parameter's name.
const OPTION_NAMES = new Set(["body", "signal", "talkiVersion", "idempotencyKey", "ifMatch"]);
const HEADER_OPTIONS = { "Idempotency-Key": "idempotencyKey", "If-Match": "ifMatch" };
const METHODS = ["get", "post", "put", "patch", "delete"];
const EXTENSIBLE = /\bnew \w+ may be added\b/i;

function fail(message) {
  console.error(`generate: ${message}`);
  process.exit(1);
}

function snake(text) {
  return text
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();
}

function camel(words) {
  return words.map((word, i) => (i === 0 ? word : word[0].toUpperCase() + word.slice(1))).join("");
}

function pascal(words) {
  return words.map((word) => word[0].toUpperCase() + word.slice(1)).join("");
}

/** The operation's words less the tag's noun, plural or singular, never as the first word. */
function shortName(operationId, tagWords) {
  const words = snake(operationId).split("_");
  const last = tagWords[tagWords.length - 1];
  const singular = [...tagWords.slice(0, -1), last.endsWith("s") ? last.slice(0, -1) : last];
  for (const noun of [tagWords, singular]) {
    for (let start = 1; start <= words.length - noun.length; start++) {
      if (noun.every((word, i) => words[start + i] === word)) {
        return [...words.slice(0, start), ...words.slice(start + noun.length)];
      }
    }
  }
  return words;
}

function comment(lines, indent) {
  const text = lines
    .join("\n")
    .replace(/\*\//g, "*\\/")
    .split("\n")
    .flatMap((line) => wrap(line, 100 - indent.length));
  while (text.length && text[text.length - 1] === "") text.pop();
  if (!text.length) return "";
  return `${indent}/**\n${text.map((line) => `${indent} *${line ? ` ${line}` : ""}`).join("\n")}\n${indent} */\n`;
}

function wrap(line, width) {
  if (line.length <= width) return [line];
  const out = [];
  let current = "";
  for (const word of line.split(" ")) {
    if (current && current.length + 1 + word.length > width) {
      out.push(current);
      current = word;
    } else {
      current = current ? `${current} ${word}` : word;
    }
  }
  if (current) out.push(current);
  return out;
}

function nullable(schema) {
  if (schema.nullable === true) return true;
  if (Array.isArray(schema.type) && schema.type.includes("null")) return true;
  return (schema.anyOf ?? schema.oneOf ?? []).some((each) => each.type === "null");
}

/** `"a" | "b" | (string & {})`, with `| null` when the schema allows it. */
function openUnion(values, withNull) {
  const f = ts.factory;
  const members = values.map((value) => f.createLiteralTypeNode(f.createStringLiteral(String(value))));
  members.push(
    f.createParenthesizedType(
      f.createIntersectionTypeNode([f.createKeywordTypeNode(ts.SyntaxKind.StringKeyword), f.createTypeLiteralNode([])]),
    ),
  );
  if (withNull) members.push(f.createLiteralTypeNode(f.createNull()));
  return f.createUnionTypeNode(members);
}

async function schemaTypes(spec) {
  const ast = await openapiTS(spec, {
    // A field with a default may be left out of a request.
    defaultNonNullable: false,
    transform(schema) {
      if (Array.isArray(schema["x-extensible-enum"])) {
        return openUnion(schema["x-extensible-enum"], nullable(schema));
      }
      if (Array.isArray(schema.enum) && EXTENSIBLE.test(schema.description ?? "")) {
        return openUnion(schema.enum, nullable(schema));
      }
      return undefined;
    },
  });
  return `${BANNER}\n${astToString(ast)}`;
}

function resolve(spec, node) {
  let current = node;
  while (current?.$ref) {
    const path = current.$ref.replace(/^#\//, "").split("/");
    current = path.reduce((value, key) => value?.[key.replace(/~1/g, "/").replace(/~0/g, "~")], spec);
    if (current === undefined) fail(`unresolved ${node.$ref}`);
  }
  return current;
}

function operationsOf(spec) {
  const operations = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const operation = item[method];
      if (!operation) continue;
      if (!operation.operationId) fail(`${method.toUpperCase()} ${path} has no operationId`);
      if (!operation.tags?.length) fail(`${operation.operationId} has no tag`);
      const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])].map((each) =>
        resolve(spec, each),
      );
      operations.push({ path, method, operation, parameters });
    }
  }
  return operations;
}

function describeOperation(spec, { path, method, operation, parameters }) {
  const id = operation.operationId;
  const pathParams = parameters.filter((each) => each.in === "path");
  const order = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
  if (
    [...order].sort().join() !==
    pathParams
      .map((each) => each.name)
      .sort()
      .join()
  ) {
    fail(`${id}: path parameters do not match ${path}`);
  }
  const query = parameters.filter((each) => each.in === "query");
  for (const each of query) {
    if (OPTION_NAMES.has(each.name)) fail(`${id}: query parameter ${each.name} clashes with an option`);
  }
  const headers = {};
  for (const each of parameters.filter((parameter) => parameter.in === "header")) {
    if (each.name === "Talki-Version") continue;
    const option = HEADER_OPTIONS[each.name];
    if (!option) fail(`${id}: header parameter ${each.name} has no option name; add it to HEADER_OPTIONS`);
    headers[option] = each;
  }
  if (parameters.some((each) => each.in === "cookie")) fail(`${id}: cookie parameters are not supported`);

  const requestBody = operation.requestBody ? resolve(spec, operation.requestBody) : null;
  if (requestBody && !requestBody.content?.["application/json"]) fail(`${id}: only JSON bodies are supported`);

  const success = [];
  const responseTypes = [];
  let binary = false;
  for (const [status, response] of Object.entries(operation.responses)) {
    const code = Number(status);
    if (!(code >= 200 && code < 300)) continue;
    success.push(code);
    const content = resolve(spec, response).content ?? {};
    const types = Object.keys(content);
    let type;
    if (code === 204 || types.length === 0) {
      type = "undefined";
    } else if (types.includes("application/json")) {
      type = `operations["${id}"]["responses"][${code}]["content"]["application/json"]`;
    } else {
      binary = true;
      type = "Blob";
    }
    if (!responseTypes.includes(type)) responseTypes.push(type);
  }
  if (!success.length) fail(`${id}: no success response`);

  let row = null;
  if (query.some((each) => each.name === "cursor")) {
    const body = resolve(spec, resolve(spec, operation.responses["200"] ?? {}).content?.["application/json"]?.schema);
    for (const field of ["data", "has_more", "next_cursor"]) {
      if (!body?.properties?.[field]) fail(`${id} takes a cursor but its 200 has no ${field}`);
    }
    row = `operations["${id}"]["responses"][200]["content"]["application/json"]["data"][number]`;
  }

  return {
    id,
    tag: operation.tags[0],
    method: method.toUpperCase(),
    path,
    summary: operation.summary ?? "",
    description: operation.description ?? "",
    pathParams: order.map((name) => pathParams.find((each) => each.name === name) ?? { name, required: true }),
    query,
    headers,
    body: requestBody ? (requestBody.required ? "required" : "optional") : null,
    bodyDescription: requestBody?.description ?? "",
    success: success.sort((a, b) => a - b),
    binary,
    responseTypes,
    row,
  };
}

function paramsType(op, typeName) {
  const parts = ["RequestOptions"];
  if (op.query.length) parts.push(`NonNullable<operations["${op.id}"]["parameters"]["query"]>`);
  const extras = [];
  if (op.body) {
    const type = `NonNullable<operations["${op.id}"]["requestBody"]>["content"]["application/json"]`;
    extras.push(
      `${comment([op.bodyDescription || "The request body, as the API reference describes it."], "  ")}  body${
        op.body === "required" ? "" : "?"
      }: ${op.body === "required" ? type : `${type} | undefined`};`,
    );
  }
  for (const [option, parameter] of Object.entries(op.headers)) {
    const text =
      option === "idempotencyKey"
        ? [
            "The write's `Idempotency-Key`. `Talki` adds a new one unless built with `autoIdempotency: false`;",
            "pass your own to send the same write again as the same one.",
            ...(parameter.required
              ? ["", "Required by this operation: without one, the API refuses the request."]
              : []),
          ]
        : [parameter.description ?? ""];
    extras.push(`${comment(text, "  ")}  ${option}?: string | undefined;`);
  }
  if (extras.length) parts.push(`{\n${extras.join("\n")}\n}`);
  const required = op.body === "required" || op.query.some((each) => each.required);
  return {
    declaration: `${comment([`Options for \`${op.id}\`.`], "")}export type ${typeName} = ${parts.join(" & ")};\n`,
    required,
  };
}

function methodDoc(op, rawResponse) {
  const lines = [];
  if (op.summary) lines.push(op.summary, "");
  if (rawResponse) {
    lines.push("Returns the whole answer: its status and headers, and `data`, the value.", "");
  } else if (op.description) {
    lines.push(op.description, "");
  }
  for (const parameter of op.pathParams) {
    lines.push(`@param ${camel(snake(parameter.name).split("_"))} - ${parameter.description ?? parameter.name}`);
  }
  lines.push(`@param params - the query, body and options; see \`${pascal(snake(op.id).split("_"))}Params\`.`);
  lines.push(`@see ${op.method} ${op.path}`);
  return comment(lines, "  ");
}

function resources(spec, operations) {
  const out = [BANNER, ""];
  out.push(
    'import type { Operation, RawResponse, RequestOptions, Requester } from "../core.js";',
    'import { type Page, PagePromise } from "../pagination.js";',
    'import type { operations } from "./schema.js";',
    "",
  );

  const tags = (spec.tags ?? []).map((tag) => tag.name);
  for (const op of operations) if (!tags.includes(op.tag)) tags.push(op.tag);

  // The operations, as the client sends them.
  out.push(
    "/** Every operation of the API, by its `operationId`: what the methods send. */",
    "export const OPERATIONS = {",
  );
  for (const op of [...operations].sort((a, b) => a.id.localeCompare(b.id))) {
    const headers = Object.entries(op.headers)
      .map(([option, parameter]) => `${option}: ${JSON.stringify(parameter.name)}`)
      .join(", ");
    out.push(
      `  ${op.id}: {`,
      `    method: "${op.method}",`,
      `    path: ${JSON.stringify(op.path)},`,
      `    query: [${op.query.map((each) => JSON.stringify(each.name)).join(", ")}],`,
      `    headers: {${headers ? ` ${headers} ` : ""}},`,
      `    body: ${op.body ? JSON.stringify(op.body) : "null"},`,
      `    success: [${op.success.join(", ")}],`,
      `    binary: ${op.binary},`,
      "  },",
    );
  }
  out.push("} as const satisfies Record<string, Operation>;", "");

  const classes = [];
  for (const tag of tags) {
    const tagWords = snake(tag).split("_");
    const property = camel(tagWords);
    const className = `${pascal(tagWords)}Resource`;
    const tagOps = operations.filter((op) => op.tag === tag);
    const shorts = tagOps.map((op) => shortName(op.id, tagWords).join("_"));
    const named = tagOps
      .map((op, i) => {
        const short = shorts[i];
        const name = shorts.filter((each) => each === short).length === 1 ? camel(short.split("_")) : op.id;
        return { op, name };
      })
      .sort((a, b) => a.name.localeCompare(b.name));
    const description = (spec.tags ?? []).find((each) => each.name === tag)?.description ?? "";
    classes.push({ tag, property, className, named, description });

    // Types.
    for (const { op } of named) {
      const base = pascal(snake(op.id).split("_"));
      op.paramsName = `${base}Params`;
      op.responseName = `${base}Response`;
      const params = paramsType(op, op.paramsName);
      op.paramsRequired = params.required;
      out.push(params.declaration);
      out.push(
        `${comment([`What \`${op.id}\` returns.`], "")}export type ${op.responseName} = ${op.responseTypes.join(" | ")};\n`,
      );
      if (op.row) {
        op.rowName = `${base}Row`;
        out.push(`${comment([`A row of \`${op.id}\`.`], "")}export type ${op.rowName} = ${op.row};\n`);
      }
    }

    const signature = (op) => {
      const args = op.pathParams.map((parameter) => `${camel(snake(parameter.name).split("_"))}: string`);
      args.push(op.paramsRequired ? `params: ${op.paramsName}` : `params: ${op.paramsName} = {}`);
      return args.join(", ");
    };
    const pathArgs = (op) =>
      `[${op.pathParams.map((parameter) => camel(snake(parameter.name).split("_"))).join(", ")}]`;
    const callArgs = (op) =>
      [...op.pathParams.map((parameter) => camel(snake(parameter.name).split("_"))), "params"].join(", ");

    // The raw twin.
    out.push(
      `${comment(
        [
          `\`talki.${property}.withRawResponse\`: the methods of \`talki.${property}\`, each returning the whole`,
          "answer, a `RawResponse` whose `data` is what the method returns. An error throws as it does there.",
        ],
        "",
      )}export class ${className}WithRawResponse {`,
      "  readonly #requester: Requester;",
      "",
      "  constructor(requester: Requester) {",
      "    this.#requester = requester;",
      "  }",
    );
    for (const { op, name } of named) {
      out.push("");
      out.push(methodDoc(op, true).trimEnd());
      if (op.row) {
        out.push(
          `  ${name}(${signature(op)}): Promise<RawResponse<Page<${op.rowName}>>> {`,
          `    return this.#requester.requestPage<${op.rowName}>(OPERATIONS.${op.id}, ${pathArgs(op)}, params);`,
          "  }",
        );
      } else {
        out.push(
          `  ${name}(${signature(op)}): Promise<RawResponse<${op.responseName}>> {`,
          `    return this.#requester.request<${op.responseName}>(OPERATIONS.${op.id}, ${pathArgs(op)}, params);`,
          "  }",
        );
      }
    }
    out.push("}", "");

    // The resource.
    out.push(
      `${comment(
        [
          `\`talki.${property}\`: ${description}`,
          "",
          "Each method sends one operation and returns its value, or throws the `ApiError` subclass for its error.",
        ],
        "",
      )}export class ${className} {`,
      "  /** The same methods, each returning the whole answer: its status and headers with the value. */",
      `  readonly withRawResponse: ${className}WithRawResponse;`,
      "",
      "  constructor(requester: Requester) {",
      `    this.withRawResponse = new ${className}WithRawResponse(requester);`,
      "  }",
    );
    for (const { op, name } of named) {
      out.push("");
      out.push(methodDoc(op, false).trimEnd());
      if (op.row) {
        out.push(
          `  ${name}(${signature(op)}): PagePromise<${op.rowName}> {`,
          `    return new PagePromise(async () => (await this.withRawResponse.${name}(${callArgs(op)})).data);`,
          "  }",
        );
      } else {
        out.push(
          `  async ${name}(${signature(op)}): Promise<${op.responseName}> {`,
          `    return (await this.withRawResponse.${name}(${callArgs(op)})).data;`,
          "  }",
        );
      }
    }
    out.push("}", "");
  }

  // The base of `Talki`.
  out.push(
    "/** One attribute per resource, each built on first use. `Talki` extends it. */",
    "export class Resources {",
    "  readonly #requester: Requester;",
    ...classes.map(({ property, className }) => `  #${property}: ${className} | undefined;`),
    "",
    "  constructor(requester: Requester) {",
    "    this.#requester = requester;",
    "  }",
  );
  for (const { property, className, description } of classes) {
    out.push(
      "",
      comment([description], "  ").trimEnd(),
      `  get ${property}(): ${className} {`,
      `    this.#${property} ??= new ${className}(this.#requester);`,
      `    return this.#${property};`,
      "  }",
    );
  }
  out.push("}", "");

  // The surface, for the test that pins it.
  out.push(
    "/** Every resource and its methods: the public surface a test pins. */",
    "export const SURFACE = {",
    ...classes.map(
      ({ property, named }) => `  ${property}: [${named.map(({ name }) => JSON.stringify(name)).join(", ")}],`,
    ),
    "} as const;",
    "",
  );
  return out.join("\n");
}

function models(spec) {
  const names = Object.keys(spec.components?.schemas ?? {}).sort();
  const out = [BANNER, 'import type { components } from "./schema.js";', ""];
  for (const name of names) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) fail(`schema ${name} is not an identifier`);
    if (RESERVED.has(name)) fail(`schema ${name} clashes with a hand-written export`);
    const description = spec.components.schemas[name].description;
    out.push(`${description ? comment([description], "") : ""}export type ${name} = components["schemas"]["${name}"];`);
  }
  out.push("");
  return out.join("\n");
}

async function render() {
  const spec = parse(await readFile(SPEC, "utf8"));
  const version = spec.info?.version;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(version ?? "")) fail(`info.version ${version} is not a dated version`);
  const operations = operationsOf(spec).map((each) => describeOperation(spec, each));
  const ids = operations.map((op) => op.id);
  const duplicate = ids.find((id, i) => ids.indexOf(id) !== i);
  if (duplicate) fail(`operationId ${duplicate} is used twice`);
  return {
    "schema.ts": await schemaTypes(spec),
    "models.ts": models(spec),
    "resources.ts": resources(spec, operations),
    "api-version.ts": `${BANNER}\n/** The dated API version this package was generated from, sent as \`Talki-Version\` by default. */\nexport const API_VERSION = "${version}";\n`,
  };
}

const files = await render();
const check = process.argv.includes("--check");
const present = await readdir(OUT).catch(() => []);
if (check) {
  const stale = [];
  for (const [name, content] of Object.entries(files)) {
    const current = await readFile(join(OUT, name), "utf8").catch(() => null);
    if (current !== content) stale.push(name);
  }
  stale.push(...present.filter((name) => !(name in files)));
  if (stale.length) {
    fail(`${stale.map((name) => relative(ROOT, join(OUT, name))).join(", ")} stale: run npm run generate`);
  }
  console.log("generate: src/generated is up to date.");
} else {
  await mkdir(OUT, { recursive: true });
  for (const [name, content] of Object.entries(files)) await writeFile(join(OUT, name), content);
  for (const name of present.filter((each) => !(each in files))) {
    fail(`${relative(ROOT, join(OUT, name))} is not generated: remove it`);
  }
  console.log(`generate: wrote ${Object.keys(files).length} files to ${relative(ROOT, OUT)}.`);
}
